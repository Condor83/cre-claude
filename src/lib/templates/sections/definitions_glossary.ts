import type { TemplateContext } from '../context.js';

export function render(_ctx: TemplateContext): string {
	return `
<p><strong>DEFINITIONS AND GLOSSARY OF TERMS</strong></p>

<p><strong>Market Value:</strong> The most probable price which a property should bring in
a competitive and open market under all conditions requisite to a fair sale, the buyer
and seller each acting prudently and knowledgeably, and assuming the price is not affected
by undue stimulus.</p>

<p><strong>Fee Simple Estate:</strong> Absolute ownership unencumbered by any other interest
or estate, subject only to the limitations imposed by the governmental powers of taxation,
eminent domain, police power, and escheat.</p>

<p><strong>Leased Fee Interest:</strong> The ownership interest held by the landlord (lessor),
which includes the right to receive the contract rent specified in the lease plus the
reversionary right when the lease expires.</p>

<p><strong>Leasehold Interest:</strong> The right held by the lessee (tenant) to use and
occupy real estate for a stated term and under the conditions specified in the lease.</p>

<p><strong>Highest and Best Use:</strong> The reasonably probable use of property that
results in the highest value. The four criteria that the highest and best use must meet
are: legally permissible, physically possible, financially feasible, and maximally
productive.</p>

<p><strong>Effective Date:</strong> The date on which the analyses, opinions, and advice in
an appraisal, review, or consulting report apply.</p>

<p><strong>Exposure Time:</strong> The estimated length of time that the property interest
being appraised would have been offered on the market prior to the hypothetical
consummation of a sale at market value on the effective date of the appraisal.</p>

<p><strong>Marketing Time:</strong> An opinion of the amount of time it might take to sell
a real or personal property interest at the concluded market value level during the period
immediately after the effective date of an appraisal.</p>

<p><strong>Net Operating Income (NOI):</strong> The actual or anticipated net income that
remains after all operating expenses are deducted from effective gross income, but before
mortgage debt service and book depreciation.</p>

<p><strong>Capitalization Rate:</strong> Any rate used to convert income into value. An
overall capitalization rate (OAR) is the ratio of net operating income to the total value
of the property.</p>

<p><strong>Gross Building Area (GBA):</strong> The total floor area of a building, including
below-grade space but excluding unenclosed areas, measured from the exterior of the walls.</p>

<p><strong>Net Rentable Area (NRA):</strong> The floor area of a building available for rent
to tenants. It is the gross building area less common areas such as stairwells, hallways,
and mechanical rooms.</p>

<p><strong>Replacement Cost:</strong> The estimated cost to construct, at current prices as
of the effective date of the appraisal, a substitute for the building being appraised,
using modern materials and current standards, design, and layout.</p>

<p><strong>Depreciation:</strong> A loss in value from any cause. In appraisal, depreciation
is categorized as physical deterioration, functional obsolescence, or external
(economic) obsolescence.</p>
`;
}
